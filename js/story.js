// «Главное» для отчета и экрана клиента: связный вывод из замеров быстрого теста разными способами объяснения.
// Только измеренное и задача тренировки (docs/legal_texts): без состояний мышц, диагнозов и связи с болью.
// Способы: вывод одной фразой, цепочка с числами, образ (аналогия), проверка на себе, с чего начинаем, привычка на день, как поймем, что стало лучше.
import { isOut } from './quick-metrics.js';

const n1 = v => String(Math.round(Math.abs(v) * 10) / 10).replace('.', ',');
/** Значение показателя: среднее по видам, только правдоподобные и вне погрешности. */
function val(by, views, key) {
  const ms = views.map(id => ((by || {})[id] || []).find(m => m.key === key)).filter(m => m && !m.suspect);
  if (!ms.length) return null; const o = ms.filter(isOut), use = o.length ? o : ms, out = o.length > 0;
  // число как в «Измерено»: среднее по видам, где показатель вне погрешности (спереди 0,8° в пределах и сзади 3,4° дают 3,4°, а не 2,1°)
  const v = use.reduce((s, m) => s + m.v, 0) / use.length;
  return { v, out, unit: ms[0].unit.trim() === '°' ? '°' : ms[0].unit.includes('см') ? ' см' : '% роста', err: ms[0].err };
}
const fmt = x => n1(x.v) + x.unit;

export function story(by) {
  const S = ['right', 'left'], FB = ['front', 'back'];
  const hf = val(by, S, 'headForward'), sh = val(by, S, 'shoulderShift'), hp = val(by, S, 'hipShift'), kn = val(by, S, 'kneeHyper');
  const st = val(by, FB, 'shoulderTilt'), tl = val(by, FB, 'trunkLateral'), pt = val(by, FB, 'pelvicTilt'), ht = val(by, FB, 'headTilt');
  const kr = val(by, FB, 'kneeR'), kl = val(by, FB, 'kneeL'), sp = val(by, ['squat'], 'squatPelvis'), skr = val(by, ['squat'], 'squatKneeR'), skl = val(by, ['squat'], 'squatKneeL');
  const on = x => x && x.out, items = [], headOn = on(hf) && hf.v > 0;
  // 1. сагиттальная цепочка: таз, корпус, голова
  if (on(hp) && hp.v > 0 && sh && sh.v < 0 && on(sh)) items.push({ key: 'sway', sc: Math.abs(hp.v) / hp.err + Math.abs(sh.v) / sh.err,
    short: 'таз подан вперед, а верх корпуса отклонен назад',
    chain: [`Таз впереди стоп на ${fmt(hp)}`, `Плечи позади таза на ${fmt(sh)}`, ...(headOn ? [`Голова впереди плеча на ${n1(hf.v)}°`] : [])],
    like: 'Как башня из кубиков: нижний кубик сдвинули вперед, верхний отклонился назад' + (headOn ? ', а самый верхний (голова) тянется вперед, чтобы башня не упала.' : ', чтобы башня не упала.'),
    try: 'Встаньте боком к зеркалу и нарочно подайте таз вперед: плечи сами уйдут назад' + (headOn ? ', а голова вперед' : '') + '. Теперь верните таз над стопами и почувствуйте разницу.',
    start: 'Начинаем снизу: сначала таз над стопами, потом плечи и голова. Верх выравнивается легче, когда низ стоит ровно.',
    habit: 'Стоя в очереди или у плиты: вес на всю стопу, пятки чувствуются, таз над стопами, а не впереди.',
    check: `Повторный замер покажет, ближе ли таз к линии лодыжки (сейчас ${fmt(hp)}).` });
  else if (on(sh) && sh.v > 0) items.push({ key: 'lean', sc: Math.abs(sh.v) / sh.err,
    short: 'корпус наклонен вперед от таза',
    chain: [...(on(hp) ? [`Таз ${hp.v > 0 ? 'впереди' : 'позади'} стоп на ${fmt(hp)}`] : []), `Плечи впереди таза на ${fmt(sh)}`, ...(headOn ? [`Голова впереди плеча на ${n1(hf.v)}°`] : [])],
    like: 'Как человек с тяжелым рюкзаком спереди: чтобы не упасть вперед, телу приходится все время себя придерживать.',
    try: 'Встаньте ровно и медленно наклонитесь вперед от щиколоток, не сгибаясь: почувствуйте, как включаются икры. Так телу приходится держать наклон весь день.',
    start: 'Начинаем с корпуса: вернуть плечи над тазом. Голова встанет ровнее вслед за ними.',
    habit: 'За столом: сядьте глубже, спина у спинки, экран на уровне глаз.',
    check: `Повторный замер покажет, ближе ли плечо к линии таза (сейчас ${fmt(sh)}).` });
  // 2. голова отдельно, если нет цепочки выше
  if (headOn && !items.length) items.push({ key: 'head', sc: hf.v / hf.err,
    short: 'голова впереди плеча',
    chain: [`Голова впереди плеча на ${n1(hf.v)}°`],
    like: 'Голова весит около 5 кг, как шар для боулинга. Держать его над плечом легко, а чуть впереди нужно постоянное усилие.',
    try: 'Встаньте спиной к стене: пятки, ягодицы и лопатки касаются стены. Достает ли затылок до стены без запрокидывания головы?',
    start: 'Начинаем с плеч и верха спины: голове проще держаться ровно, когда ей есть на что опереться.',
    habit: 'Телефон поднимайте к глазам, а не опускайте голову к телефону.',
    check: `Повторный замер покажет угол головы (сейчас ${n1(hf.v)}°).` });
  // 3. перекос вбок
  const lat = [on(tl) && `Корпус смещен ${tl.v > 0 ? 'вправо' : 'влево'} на ${fmt(tl)}`, on(st) && `${st.v > 0 ? 'Правое' : 'Левое'} плечо ниже на ${fmt(st)}`, on(pt) && `${pt.v > 0 ? 'Правая' : 'Левая'} сторона таза ниже на ${fmt(pt)}`, on(ht) && `Голова наклонена к ${ht.v > 0 ? 'правому' : 'левому'} плечу на ${fmt(ht)}`].filter(Boolean);
  if (lat.length) { const xs = [tl, st, pt, ht].filter(on); items.push({ key: 'side', sc: Math.max(...xs.map(x => Math.abs(x.v) / x.err)),
    short: on(tl) ? `корпус смещен ${tl.v > 0 ? 'вправо' : 'влево'}` : on(st) ? `${st.v > 0 ? 'правое' : 'левое'} плечо ниже` : on(pt) ? `таз ниже ${pt.v > 0 ? 'справа' : 'слева'}` : `голова наклонена ${ht.v > 0 ? 'вправо' : 'влево'}`,
    chain: lat,
    like: 'Как рюкзак на одном плече: тело выравнивает себя по-своему, и одна сторона все время работает больше другой.',
    try: 'Встаньте ровно и закройте глаза на 10 секунд. На какой ноге вес чувствуется больше? Запомните и сравните через месяц.',
    start: 'Работаем с двух сторон по-разному: где задача «укрепить», там больше подходов, где «расслабить», там мягкая растяжка.',
    habit: 'Сумку и ребенка на руках чередуйте: одна сторона, потом другая.',
    check: 'Повторный замер покажет, ровнее ли линии плеч и таза.' }); }
  // 4. колени
  const kv = [[kr, 'правого'], [kl, 'левого']].filter(([x]) => on(x)).map(([x, s]) => `Ось ${s} колена уходит ${x.v > 0 ? 'внутрь' : 'наружу'} на ${fmt(x)}`);
  const sq = [on(sp) && `В полуприседе ${sp.v > 0 ? 'правая' : 'левая'} сторона таза ниже на ${fmt(sp)}`, ...[[skr, 'правое'], [skl, 'левое']].filter(([x]) => on(x)).map(([x, s]) => `В полуприседе ${s} колено уходит ${x.v > 0 ? 'внутрь' : 'наружу'} на ${fmt(x)}`)].filter(Boolean);
  if (kv.length || sq.length) { const xs = [kr, kl, sp, skr, skl].filter(on); items.push({ key: 'knee', sc: Math.max(...xs.map(x => Math.abs(x.v) / x.err)) * .9,
    short: kv.length ? 'ось колена отклонена' : 'в полуприседе таз опускается на одну сторону',
    chain: [...kv, ...sq],
    like: 'Колено похоже на дверную петлю: оно работает лучше всего, когда движется в одной плоскости с бедром и стопой.',
    try: 'Медленно присядьте перед зеркалом: смотрит ли колено туда же, куда второй палец стопы? Сравните правую и левую ногу.',
    start: 'В упражнениях следите за одним: колено над вторым пальцем стопы.',
    habit: 'На лестнице: колено над стопой, без заваливания внутрь или наружу.',
    check: 'Повторный замер покажет ось колена в стойке и в полуприседе.' }); }
  items.sort((a, b) => b.sc - a.sc);
  // сагиттальная цепочка первой, если она есть: низ тела держит верх
  const sag = items.findIndex(x => x.key === 'sway' || x.key === 'lean'); if (sag > 0) items.unshift(items.splice(sag, 1)[0]);
  const top = items.slice(0, 3);
  const cap = t => t[0].toUpperCase() + t.slice(1), main = top.length ? cap(top[0].short) + '.' + (top[1] ? ' Еще: ' + top[1].short + '.' : '') : '';
  return { main, items: top };
}
