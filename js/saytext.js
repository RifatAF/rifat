// Текст озвучки упражнения: название, сторона, шаги и подсказка, на «вы». Один и тот же текст использует приложение
// (ищет запись по точному совпадению) и сборка (scripts/fetch-assets.mjs озвучивает фразы, для которых записи еще нет).
export function sayText(e) {
  const m = /\((левая|правая) сторона\)/.exec(e.title || ''), name = String(e.title || '').split(' (')[0];
  return [name + (m ? ', ' + m[1] + ' сторона' : '') + '.', ...(e.steps || []), e.check || ''].join(' ').replace(/\s+/g, ' ').trim();
}
